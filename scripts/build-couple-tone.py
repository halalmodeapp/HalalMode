"""Samples the couple scene's colours for the phone's halftone dots.

The scene is many separately painted layers, so this draws them where they sit
at rest, shrinks the result to a small grid, and writes it as a base64 string
into src/components/auth/coupleTone.ts. The phone reads colours from it to size
and tint its dots; nothing else about the scene is baked.

Run after the layers change:  python scripts/build-couple-tone.py
"""
import base64
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
LAYERS = ROOT / "src/components/auth/coupleSceneLayers.ts"
OUT = ROOT / "src/components/auth/coupleTone.ts"
GRID = (96, 64)

text = LAYERS.read_text(encoding="utf-8")
world = re.search(r"COUPLE_WORLD = \{ width: (\d+), height: (\d+)", text)
WORLD = (int(world.group(1)), int(world.group(2)))
layers = re.findall(r"\{ key: '(\w+)', file: '([^']+)', depth: [-\d.]+, x: (-?\d+), y: (-?\d+), width: (\d+), height: (\d+) \}", text)

canvas = Image.new("RGBA", WORLD, (47, 107, 216, 255))
for key, file, x, y, w, h in layers:
    image = Image.open(ROOT / "site/img/scene" / file).convert("RGBA").resize((int(w), int(h)), Image.LANCZOS)
    layer = Image.new("RGBA", WORLD, (0, 0, 0, 0))
    layer.paste(image, (int(x), int(y)))
    canvas = Image.alpha_composite(canvas, layer)

small = canvas.convert("RGB").resize(GRID, Image.BOX)
data = base64.b64encode(small.tobytes()).decode("ascii")
OUT.write_text(
    "// Generated by scripts/build-couple-tone.py. Do not edit by hand.\n\n"
    "/** The couple scene at rest, shrunk to a grid of RGB bytes (base64), for the halftone dots. */\n"
    f"export const COUPLE_TONE = {{ width: {GRID[0]}, height: {GRID[1]}, data: '{data}' }} as const;\n",
    encoding="utf-8",
)
print("wrote", OUT, len(data), "chars")
