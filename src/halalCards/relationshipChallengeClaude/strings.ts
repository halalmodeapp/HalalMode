const TRANSLATIONS: Record<string, Partial<Record<RcCopyKey, string>>> = { ar: AR };

export function rcCopy(language: string, key: RcCopyKey, params?: Record<string, string | number>): string {
  let message: string = TRANSLATIONS[language]?.[key] ?? EN[key];
  for (const [name, value] of Object.entries(params ?? {})) message = message.replaceAll(`{{${name}}}`, String(value));
  return message;
}

/** Content keys are strings in the scenario data; unknown keys show themselves. */
export function rcText(language: string, key: string, params?: Record<string, string | number>): string {
  return key in EN ? rcCopy(language, key as RcCopyKey, params) : key;
}

